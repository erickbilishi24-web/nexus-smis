CREATE TABLE `school_applications` (
	`id` int AUTO_INCREMENT NOT NULL,
	`referenceNumber` varchar(40) NOT NULL,
	`schoolName` varchar(200) NOT NULL,
	`schoolType` varchar(80) NOT NULL,
	`county` varchar(100) NOT NULL,
	`subcounty` varchar(100),
	`town` varchar(100),
	`schoolPhone` varchar(40) NOT NULL,
	`schoolEmail` varchar(320),
	`applicantName` varchar(160) NOT NULL,
	`applicantPosition` varchar(120) NOT NULL,
	`applicantPhone` varchar(40) NOT NULL,
	`applicantEmail` varchar(320) NOT NULL,
	`message` text,
	`privateNotes` text,
	`status` enum('new','under_review','approved','rejected','onboarded') NOT NULL DEFAULT 'new',
	`reviewedByUserId` int,
	`reviewedAt` timestamp,
	`schoolId` int,
	`onboardedAt` timestamp,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `school_applications_id` PRIMARY KEY(`id`),
	CONSTRAINT `school_applications_referenceNumber_unique` UNIQUE(`referenceNumber`)
);
