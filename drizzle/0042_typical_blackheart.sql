CREATE TABLE `learner_leave_out_passes` (
	`id` int AUTO_INCREMENT NOT NULL,
	`schoolId` int NOT NULL,
	`learnerId` int NOT NULL,
	`passNumber` varchar(50) NOT NULL,
	`reason` varchar(500) NOT NULL,
	`intendedDepartureAt` timestamp NOT NULL,
	`expectedReturnAt` timestamp,
	`destination` varchar(255),
	`collectorName` varchar(160),
	`collectorRelationship` varchar(80),
	`collectorVerification` varchar(120),
	`guardianVerified` int NOT NULL DEFAULT 0,
	`status` enum('draft','pending_approval','approved','rejected','departed','returned','cancelled','expired') NOT NULL DEFAULT 'pending_approval',
	`initiatedByUserId` int NOT NULL,
	`approvedByUserId` int,
	`approvedAt` timestamp,
	`departedAt` timestamp,
	`departedByUserId` int,
	`returnedAt` timestamp,
	`returnedByUserId` int,
	`remarks` text,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `learner_leave_out_passes_id` PRIMARY KEY(`id`),
	CONSTRAINT `leave_out_school_pass_school_number_unique` UNIQUE(`schoolId`,`passNumber`)
);
